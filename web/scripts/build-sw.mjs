/**
 * Builds the Ignit service worker: `src/features/pwa/sw-source.ts` -> `public/sw.js`.
 *
 * Emits a classic (IIFE) script because some browsers still refuse ES modules in
 * `navigator.serviceWorker.register()`. esbuild already ships with the Astro/Vite
 * toolchain, so it is resolved from the workspace instead of adding a dependency.
 */
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entryPoint = path.join(projectRoot, 'src/features/pwa/sw-source.ts');
const outfile = path.join(projectRoot, 'public/sw.js');

const pkgRequire = createRequire(path.join(projectRoot, 'package.json'));

async function loadEsbuild() {
	try {
		return await import('esbuild');
	} catch {
		// pnpm's strict layout does not expose transitive dependencies at the root,
		// so fall back to the copy installed for Astro.
		try {
			const astroRequire = createRequire(pkgRequire.resolve('astro/package.json'));
			return astroRequire('esbuild');
		} catch {
			throw new Error(
				'esbuild is not available in web/node_modules. Run `pnpm install` in web/ first.',
			);
		}
	}
}

const esbuild = await loadEsbuild();

await esbuild.build({
	entryPoints: [entryPoint],
	outfile,
	bundle: true,
	format: 'iife',
	target: 'es2020',
	minify: true,
	legalComments: 'none',
	sourcemap: false,
	platform: 'browser',
	logLevel: 'warning',
	banner: {
		js: [
			'/* Ignit service worker — generated by web/scripts/build-sw.mjs. Do not edit directly. */',
			'// @ts-nocheck',
		].join('\n'),
	},
});

console.log(`built ${path.relative(projectRoot, outfile)} from ${path.relative(projectRoot, entryPoint)}`);
