import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
	alias(libs.plugins.kotlin.multiplatform)
	alias(libs.plugins.compose.multiplatform)
	alias(libs.plugins.compose.compiler)
}

// The API environment is a build-time choice between two explicit profiles: `production` (the default)
// and a local backend via -Pignit.environment=local. The two differ in both the auth endpoint and the
// REST path, so the profile carries the base URL and both paths instead of a single URL. The values are
// baked into generated constants so the entry point never hardcodes an environment. No extra
// dependency: the task writes the file itself.

/** One API environment profile: exactly what the generated `IgnitApiConfig` bakes into the app. */
data class IgnitApiProfile(
	val apiBaseUrl: String,
	val signInPath: String,
	val booksPath: String,
)

/** Escapes a value so it can be written inside a Kotlin string literal. */
fun kotlinString(value: String): String = value.replace("\\", "\\\\").replace("\"", "\\\"")

val ignitEnvironment = providers.gradleProperty("ignit.environment").orElse("production")

// Resolved and validated while configuring, so an unknown profile fails every invocation instead of
// only the ones that happen to run the generate task.
val ignitApiProfile = when (val environment = ignitEnvironment.get()) {
	"production" -> IgnitApiProfile(
		apiBaseUrl = "https://ignit.ignit677.workers.dev",
		signInPath = "/api/auth/sign-in/email",
		booksPath = "/api/books",
	)
	"local" -> IgnitApiProfile(
		// Desktop reaches the backend on the developer machine directly at localhost.
		apiBaseUrl = "http://localhost:3000",
		signInPath = "/api/auth/dev-login",
		booksPath = "/books",
	)
	else -> throw GradleException(
		"Unknown ignit.environment '$environment'. Use 'production' (the default) or 'local': " +
			"those are the only API profiles the app builds against.",
	)
}
val ignitApiConfigDir = layout.buildDirectory.dir("generated/ignitApiConfig/kotlin")

val generateIgnitApiConfig = tasks.register("generateIgnitApiConfig") {
	val profile = ignitApiProfile
	val outputDir = ignitApiConfigDir
	inputs.property("apiBaseUrl", profile.apiBaseUrl)
	inputs.property("signInPath", profile.signInPath)
	inputs.property("booksPath", profile.booksPath)
	outputs.dir(outputDir)
	doLast {
		val source = outputDir.get().file("dev/ignit/desktop/IgnitApiConfig.kt").asFile
		source.parentFile.mkdirs()
		source.writeText(
			buildString {
				appendLine("// Generated by :platforms:desktop:generateIgnitApiConfig from ignit.environment. Do not edit.")
				appendLine("package dev.ignit.desktop")
				appendLine()
				appendLine("internal object IgnitApiConfig {")
				appendLine("\tinternal const val API_BASE_URL: String = \"${kotlinString(profile.apiBaseUrl)}\"")
				appendLine("\tinternal const val SIGN_IN_PATH: String = \"${kotlinString(profile.signInPath)}\"")
				appendLine("\tinternal const val BOOKS_PATH: String = \"${kotlinString(profile.booksPath)}\"")
				appendLine("}")
			},
		)
	}
}

kotlin {
	jvm()

	sourceSets {
		jvmMain {
			// Compile the generated constant; the srcDir carries the task as an implicit dependency.
			kotlin.srcDir(generateIgnitApiConfig)
		}
		jvmMain.dependencies {
			implementation(project(":core:application"))
			implementation(project(":core:domain"))
			implementation(project(":adapters:driving:ui-compose"))
			implementation(project(":adapters:driven:http-api"))
			implementation(project(":adapters:driven:persistence"))
			implementation(project(":adapters:driven:auth-session"))
			implementation(project(":adapters:driven:preferences"))
			implementation(compose.desktop.currentOs)
			implementation(compose.material3)
			implementation(libs.kotlinx.coroutines.swing)
		}
	}
}

// Every Kotlin compile task in this module reads the generated constant.
tasks.matching { task -> task.name.startsWith("compile") }.configureEach {
	dependsOn(generateIgnitApiConfig)
}

compose.desktop {
	application {
		mainClass = "dev.ignit.desktop.MainKt"
		nativeDistributions {
			targetFormats(TargetFormat.Dmg, TargetFormat.Msi, TargetFormat.Deb)
			packageName = "Ignit"
			packageVersion = "2.0.0"
		}
	}
}
