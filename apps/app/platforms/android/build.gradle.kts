plugins {
	alias(libs.plugins.kotlin.multiplatform)
	alias(libs.plugins.android.application)
	alias(libs.plugins.compose.multiplatform)
	alias(libs.plugins.compose.compiler)
}

// The API base URL is a build-time choice: production by default, a local backend via
// -Pignit.apiBaseUrl=http://10.0.2.2:3000. The value is baked into a generated constant so the
// entry point never hardcodes an environment. No extra dependency: the task writes the file itself.
val ignitApiBaseUrl = providers.gradleProperty("ignit.apiBaseUrl")
	.orElse("https://ignit.ignit677.workers.dev")
val ignitApiConfigDir = layout.buildDirectory.dir("generated/ignitApiConfig/kotlin")

val generateIgnitApiConfig = tasks.register("generateIgnitApiConfig") {
	val baseUrl = ignitApiBaseUrl
	val outputDir = ignitApiConfigDir
	inputs.property("apiBaseUrl", baseUrl.get())
	outputs.dir(outputDir)
	doLast {
		val escaped = baseUrl.get().replace("\\", "\\\\").replace("\"", "\\\"")
		val source = outputDir.get().file("dev/ignit/android/IgnitApiConfig.kt").asFile
		source.parentFile.mkdirs()
		source.writeText(
			buildString {
				appendLine("// Generated by :platforms:android:generateIgnitApiConfig from ignit.apiBaseUrl. Do not edit.")
				appendLine("package dev.ignit.android")
				appendLine()
				appendLine("internal object IgnitApiConfig {")
				appendLine("\tinternal const val API_BASE_URL: String = \"$escaped\"")
				appendLine("}")
			},
		)
	}
}

kotlin {
	androidTarget {
		compilations.all { kotlinOptions { jvmTarget = "17" } }
	}

	sourceSets {
		androidMain {
			// Compile the generated constant; the srcDir carries the task as an implicit dependency.
			kotlin.srcDir(generateIgnitApiConfig)
		}
		androidMain.dependencies {
			implementation(project(":core:application"))
			implementation(project(":core:domain"))
			implementation(project(":adapters:driving:ui-compose"))
			implementation(project(":adapters:driven:http-api"))
			implementation(project(":adapters:driven:persistence"))
			implementation(project(":adapters:driven:auth-session"))
			implementation(project(":adapters:driven:preferences"))
			implementation(compose.material3)
			implementation(libs.androidx.activity.compose)
		}
	}
}

// Every Kotlin compile task in this module reads the generated constant.
tasks.matching { task -> task.name.startsWith("compile") }.configureEach {
	dependsOn(generateIgnitApiConfig)
}

